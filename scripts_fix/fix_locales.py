def insert_before_close(src, section, add):
    pat = re.compile(r'(\n  ' + section + r': \{.*?)(\n  \},)', re.S)
    m = pat.search(src)
    assert m, f'{section} not found'
    return src[:m.end(1)] + '\n' + add + src[m.end(1):]

base = '/workspace/E-Literacy-Citizen-App-main 2/i18n/locales/'
for lang in PROFILE_ADD:
    path = base + lang + '.ts'
    src = open(path, encoding='utf-8').read()
    src = insert_before_close(src, 'profile', PROFILE_ADD[lang])
    src = insert_before_close(src, 'settings', SETTINGS_ADD[lang])
    open(path, 'w', encoding='utf-8').write(src)
    print('updated', path)
